"""Schemas for the internal linking studio.

Design principles:
  - URLs are validated against the connected site's host. External URLs
    are rejected for internal-link purposes.
  - Suggestions are advisory. The user reviews and approves.
  - Anchor text duplication warnings are surfaced, not enforced.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field


LinkType = Literal[
    "contextual",  # inline within content
    "related_product",
    "related_article",
    "category",
    "brand",
    "footer_related",
]

LinkLabel = Literal[
    "read_more",
    "related_products",
    "related_article",
    "learn_more",
    "custom",
]


class SearchResultItem(BaseModel):
    """One item in the internal-link search results."""

    model_config = ConfigDict(extra="forbid")

    id: int
    type: str = Field(
        ...,
        description="post | page | product | category | product_category",
        examples=["product"],
    )
    title: str = ""
    url: str = ""
    slug: str = ""
    excerpt: str = ""


class SearchResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    items: list[SearchResultItem] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)


class SuggestedLink(BaseModel):
    """A suggestion generated by the service, awaiting user review."""

    model_config = ConfigDict(extra="forbid")

    target_id: int
    target_type: str
    title: str
    url: str
    score: float = Field(..., ge=0.0, le=1.0)
    reason: str = ""
    suggested_anchor: str = ""


class SuggestResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    items: list[SuggestedLink] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)


class ValidateUrlRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    url: str = Field(..., min_length=1, max_length=2000)


class ValidateUrlResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    ok: bool
    reason: str = ""
    normalized_url: str = ""
    host: str = ""


class AnchorTextCheckRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    anchor_text: str = Field(..., min_length=1, max_length=200)
    existing_anchors: list[str] = Field(
        default_factory=list,
        description="Anchor texts already used in the same content.",
    )


class AnchorTextCheckResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    warnings: list[str] = Field(default_factory=list)
    exact_match_count: int = 0